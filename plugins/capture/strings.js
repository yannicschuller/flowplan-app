const escape = (value) => value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

// One dictionary per language with its type spelled out (the Swift type
// checker is slow on large untyped literals).
function swiftTable() {
  const tables = LANGS.map((lang, index) => {
    const entries = Object.entries(strings).map(([key, values]) => `    "${key}": "${escape(values[index])}",`);
    return `  private static let ${lang}: [String: String] = [\n${entries.join("\n")}\n  ]`;
  });
  return `// Generated by plugins/with-capture.js from plugins/capture/strings.js.
import Foundation

enum FPSStrings {
${tables.join("\n\n")}

  private static func table(_ lang: String) -> [String: String] {
    if lang == "de" { return de }
    if lang == "fr" { return fr }
    return en
  }

  /// The profile's language when the app handed one over, else the phone's.
  static var lang: String = Bundle.preferredLocalizations(from: ${JSON.stringify(LANGS)}, forPreferences: Locale.preferredLanguages).first ?? "en"

  static func t(_ key: String, _ values: [String: String] = [:]) -> String {
    var text: String = table(lang)[key] ?? en[key] ?? key
    for (name, value) in values {
      text = text.replacingOccurrences(of: "{" + name + "}", with: value)
    }
    return text
  }
}
`;
}

module.exports = { LANGS, strings, swiftTable };
